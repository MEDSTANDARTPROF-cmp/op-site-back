def get_category_id(course: dict) -> int:
    """Вычисляет Yandex categoryId для курса."""
    # 1) Точный маппинг по id подкатегории в цепочке
    for parent_id in course.get("ancestors", []):
        if parent_id in SUBCATEGORY_TO_YANDEX:
            return SUBCATEGORY_TO_YANDEX[parent_id]

    # 2) По ключевым словам в названии
    title = course["pagetitle"].lower()
    for pattern, cat_id in KEYWORD_TO_YANDEX:
        if re.search(pattern, title, re.IGNORECASE):
            return cat_id

    # 3) Фолбэк: для root 63 (рабочие профессии) — Инженерия, иначе Разное
    if course.get("root_id") == 63:
        return 1007
    return 1099


# Определение типа обучения и результата
def get_offer_type_and_result(course: dict) -> tuple[str, str]:
    """Возвращает (Тип обучения, Результат обучения).

    По корню:
    - 61 Переподготовка → Профессия + Диплом
    - 46 Повышение квалификации → Курс + Удостоверение
    - 63 Рабочие профессии → Курс + Удостоверение
    """
    root = course.get("root_id")
    if root == 61:
        return "Профессия", "Диплом"
    return "Курс", "Удостоверение"
